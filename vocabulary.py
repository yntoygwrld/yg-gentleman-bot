# Phrases that should be matched as whole words only
# (to avoid matching partial words)
WHOLE_WORD_ONLY = {
    "yo", "ay", "g", "bro", "bruh", "fam", "cap", "bet", "fire", "lit",
    "mid", "sus", "ice", "bag", "rn", "f", "oof", "tea", "beef", "man",
}

def get_correction(text: str) -> tuple[str, str] | None:
    """
    Check if text contains any YN phrases and return the phrase and correction.
    Returns tuple of (yn_phrase, yg_correction) or None if no match.
    """
    text_lower = text.lower()

    # Sort by length (longest first) to match multi-word phrases before single words
    sorted_phrases = sorted(VOCABULARY.keys(), key=len, reverse=True)

    for yn_phrase in sorted_phrases:
        if yn_phrase in WHOLE_WORD_ONLY:
            # Check for whole word match
            import re
            pattern = r'\b' + re.escape(yn_phrase) + r'\b'
            if re.search(pattern, text_lower):
                return (yn_phrase, VOCABULARY[yn_phrase])
        else:
            if yn_phrase in text_lower:
                return (yn_phrase, VOCABULARY[yn_phrase])

    return None


